"""Structural ports: application never imports SQLAlchemy adapters."""
from typing import Any, Protocol

class Repository(Protocol):
    def get_by_id(self, entity_id: Any) -> Any | None: ...
    def list_all(self) -> list[Any]: ...
    def create(self, data: dict[str, Any]) -> Any: ...
    def update(self, entity_id: Any, data: dict[str, Any]) -> Any | None: ...
    def delete(self, entity_id: Any) -> bool: ...

class UserRepository(Repository, Protocol):
    def get_by_email(self, email: str) -> Any | None: ...
    def create_user(self, data: dict[str, Any]) -> Any: ...
    def update_user(self, entity_id: int, data: dict[str, Any]) -> Any | None: ...
    def set_active(self, entity_id: int, active: bool) -> Any | None: ...
