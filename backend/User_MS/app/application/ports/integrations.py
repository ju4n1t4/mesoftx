from typing import Any, Protocol

class IntegrationRepository(Protocol):
    def list_connections(self) -> list[Any]: ...
    def get_connection(self, connection_id: int) -> Any | None: ...
    def save_connection(self, data: dict[str, Any], connection_id: int | None = None) -> Any: ...
    def start_run(self, connection_id: int, key: str, actor_id: int) -> tuple[Any, bool]: ...
    def finish_run(self, run_id: int, records: list[tuple[str, dict[str, Any]]]) -> Any: ...
    def fail_run(self, run_id: int, code: str) -> Any: ...
    def list_runs(self, connection_id: int) -> list[Any]: ...
    def list_records(self, connection_id: int, offset: int, limit: int) -> list[Any]: ...

class SecretVault(Protocol):
    def encrypt(self, value: str) -> str: ...
    def decrypt(self, value: str) -> str: ...

class ExternalJsonClient(Protocol):
    def validate_url(self, origin: str, path: str) -> str: ...
    async def fetch(self, connection: Any, secret: str | None) -> Any: ...
