\connect users_db
BEGIN;
CREATE TABLE IF NOT EXISTS schema_migrations (
    version varchar(100) PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE TABLE IF NOT EXISTS integration_connections (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL UNIQUE,
    base_url varchar(500) NOT NULL,
    resource_path varchar(500) NOT NULL DEFAULT '/',
    records_path varchar(200) NOT NULL DEFAULT '',
    external_id_field varchar(100) NOT NULL DEFAULT 'id',
    auth_type varchar(20) NOT NULL DEFAULT 'none' CHECK (auth_type IN ('none', 'bearer', 'api_key')),
    encrypted_secret text,
    enabled boolean NOT NULL DEFAULT false,
    created_by integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    updated_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE TABLE IF NOT EXISTS integration_sync_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id integer NOT NULL REFERENCES integration_connections(id) ON DELETE RESTRICT,
    idempotency_key varchar(100) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'succeeded', 'failed')),
    records_count integer NOT NULL DEFAULT 0,
    error_code varchar(100),
    started_by integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    started_at timestamptz NOT NULL DEFAULT current_timestamp,
    finished_at timestamptz,
    UNIQUE (connection_id, idempotency_key)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_integration_running
    ON integration_sync_runs(connection_id) WHERE status = 'running';
CREATE TABLE IF NOT EXISTS integration_records (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id integer NOT NULL REFERENCES integration_connections(id) ON DELETE RESTRICT,
    external_id varchar(255) NOT NULL,
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    last_run_id integer NOT NULL REFERENCES integration_sync_runs(id) ON DELETE RESTRICT,
    updated_at timestamptz NOT NULL DEFAULT current_timestamp,
    UNIQUE (connection_id, external_id)
);
INSERT INTO permissions(code, name, description)
